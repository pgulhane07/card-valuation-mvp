-- Card valuation MVP: PostgreSQL 14+
-- Synthetic completed-sale data. Verification is assumed upstream for this prototype.
BEGIN;

CREATE TABLE IF NOT EXISTS players (
    player_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_key TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    sport TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS card_sets (
    set_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_key TEXT NOT NULL UNIQUE,
    sport TEXT NOT NULL,
    release_year INTEGER NOT NULL CHECK (release_year BETWEEN 1850 AND 2200),
    manufacturer TEXT NOT NULL,
    set_name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS card_variants (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_key CHAR(64) NOT NULL UNIQUE,
    -- Broad indexed lookup groups. They are NOT unique identifiers.
    group_key TEXT NOT NULL,  -- sport:year:manufacturer:player_key
    cohort_key TEXT NOT NULL, -- sport:year:manufacturer (without player)
    set_id BIGINT NOT NULL REFERENCES card_sets(set_id),
    player_id BIGINT NOT NULL REFERENCES players(player_id),
    card_number TEXT NOT NULL,
    parallel_code TEXT NOT NULL,
    serial_limit INTEGER CHECK (serial_limit > 0),
    image_variant_code TEXT NOT NULL DEFAULT 'NONE',
    back_variant_code TEXT NOT NULL DEFAULT 'NONE',
    autograph BOOLEAN NOT NULL DEFAULT FALSE,
    relic BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS completed_sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    external_sale_id TEXT NOT NULL,
    card_id BIGINT NOT NULL REFERENCES card_variants(card_id),
    sold_at TIMESTAMPTZ NOT NULL,
    sale_price_usd NUMERIC(12,2) NOT NULL CHECK (sale_price_usd > 0),
    grading_company TEXT NOT NULL CHECK (grading_company IN ('RAW','PSA')),
    numeric_grade NUMERIC(3,1),
    raw_condition TEXT,
    grade_bucket TEXT NOT NULL,
    -- In MVP, upstream verification is assumed; original input is preserved.
    verification_status TEXT NOT NULL DEFAULT 'ASSUMED_VERIFIED',
    raw_payload JSONB NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_external_transaction UNIQUE(source, external_sale_id),
    CONSTRAINT grade_consistency CHECK (
        (grading_company = 'RAW' AND numeric_grade IS NULL AND raw_condition IS NOT NULL)
        OR
        (grading_company = 'PSA' AND numeric_grade BETWEEN 1 AND 10 AND raw_condition IS NULL)
    )
);

-- Defined now; valuation calculation will populate this later.
CREATE TABLE IF NOT EXISTS valuation_snapshots (
    card_id BIGINT NOT NULL REFERENCES card_variants(card_id),
    grade_bucket TEXT NOT NULL,
    valuation_date DATE NOT NULL,
    method TEXT NOT NULL,
    estimated_price_usd NUMERIC(12,2),
    range_low_usd NUMERIC(12,2),
    range_high_usd NUMERIC(12,2),
    comparable_count INTEGER NOT NULL DEFAULT 0 CHECK (comparable_count >= 0),
    confidence TEXT NOT NULL,
    lookback_days INTEGER NOT NULL CHECK (lookback_days IN (90,180)),
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY(card_id,grade_bucket,valuation_date)
);

-- Candidate search on small card catalog (not the whole sales table).
CREATE INDEX IF NOT EXISTS idx_card_group ON card_variants(group_key);
CREATE INDEX IF NOT EXISTS idx_card_cohort_set ON card_variants(cohort_key,set_id);
CREATE INDEX IF NOT EXISTS idx_card_structured ON card_variants(set_id,player_id,card_number);

-- Fast retrieval for exact-card + grade + recency valuation.
CREATE INDEX IF NOT EXISTS idx_sales_card_grade_date
    ON completed_sales(card_id,grade_bucket,sold_at DESC)
    INCLUDE (sale_price_usd);

COMMIT;
